def split_for(family: str, eval_percent: int = 20) -> str:
    value = int(hashlib.sha1(family.encode('utf-8')).hexdigest()[:8], 16) % 100
    return 'eval' if value < eval_percent else 'train'


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8') as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + '\n')


def base_state(location: str = 'Старая застава') -> dict:
    return {
        'location': location,
        'hp': '12/12',
        'money': '18',
        'inventory': ['Фляга', 'Факел', 'Верёвка'],
        'npcs': ['Страж | ACTIVE | HP 10/10 | Старая застава | Наблюдает за героем.'],
        'quests': [],
        'world_events': [],
        'abilities': ['Внимательность | SKILL'],
        'effects': [],
        'action_hint': 'NONE',
    }


def t(action_type: str, name: str = '', value: str = '', details: str = '') -> dict:
    return {'type': action_type, 'name': name, 'value': value, 'details': details}


def director_row(
    rid: str,
    family: str,
    player_action: str,
    target: dict,
    *,
    state: dict | None = None,
    scene: str = 'Сумерки сгущаются у старой заставы. Камни дороги блестят после дождя.',
    world: str = 'Мрачное пограничье, где старые дороги небезопасны.',
    character: str = 'Путник, человек, авантюрист.',
    mode: str = 'PLAYER_ACTION',
    check: dict | None = None,
) -> dict:
    row = {
        'id': rid,
        'kind': 'DIRECTOR',
        'family': family,
        'split': split_for(family),
        'mode': mode,
        'current_scene': scene,
        'world': world,
        'character': character,
        'summary': '',
        'recent_events': [],
        'relevant_facts': [],
        'active_situations': '',
        'state': state or base_state(),
        'player_action': player_action,
        'target': target,
        'note': 'v3 hard contrast / identity-field correction',
    }
    if check:
        row['check'] = check
    return row


